export function calculateNextReview(currentStage: number, isCorrect: boolean): { nextStage: number; intervalDays: number; nextDueDate: string } {
  let nextStage = currentStage;
  if (isCorrect) {
    nextStage = Math.min(5, currentStage + 1);
  } else {
    nextStage = Math.max(1, currentStage - 1);
  }

  const intervalMap: Record<number, number> = {
    0: 0,
    1: 1,
    2: 3,
    3: 7,
    4: 14,
    5: 30 // Mastered
  };

  const intervalDays = intervalMap[nextStage] || 1;
  const now = new Date();
  now.setDate(now.getDate() + intervalDays);
  const nextDueDate = now.toISOString().split('T')[0];

  return {
    nextStage,
    intervalDays,
    nextDueDate
  };
}
